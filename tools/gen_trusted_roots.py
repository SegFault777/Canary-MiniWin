"""Regenerates kernel/trusted_roots.h as a COMPACT anchor table.

A trust anchor only has to say two things: "my subject is X" and "my public key is K". The old header embedded every root as
a full DER certificate (about 1.2 KB each, signature and extensions included, none of which are ever checked for an anchor).
This writes just the raw subject Name TLV plus the key, which is about a third of the size -- that is what pays for the extra
roots and for TLS 1.3 inside the kernel's size budget.

Input: every root already in the old header (so nothing that shipped is dropped) plus Mozilla's current bundle (certifi),
keeping RSA keys up to 4096 bits and NIST P-256 / P-384 keys, the only key types x509.h can verify with. Duplicates (same
subject AND key) are merged. Usage: tools/gen_trusted_roots.py  (from the repo root)"""
import re, sys, certifi
from cryptography import x509
from cryptography.hazmat.primitives import serialization
from cryptography.hazmat.primitives.asymmetric import rsa, ec

PATH = "kernel/trusted_roots.h"

def tlv(d, i):
    tag = d[i]; l = d[i + 1]; h = 2
    if l & 0x80:
        n = l & 0x7F; l = int.from_bytes(d[i + 2:i + 2 + n], "big"); h = 2 + n
    return tag, i + h, l           # tag, start of value, length

def split(der):
    """(raw subject Name TLV, kind, key bytes) -- the subject exactly as it sits in the certificate, like x509_parse() keeps it."""
    _, v, l = tlv(der, 0)                          # Certificate
    _, tv, tl = tlv(der, v)                        # tbsCertificate
    p = tv
    if der[p] == 0xA0: _, a, b = tlv(der, p); p = a + b          # version
    for _ in range(3): _, a, b = tlv(der, p); p = a + b          # serial, signature alg, issuer
    _, a, b = tlv(der, p); p = a + b                              # validity
    _, a, b = tlv(der, p); subj = der[p:a + b]; p = a + b         # subject
    return subj

def key_of(cert):
    k = cert.public_key()
    if isinstance(k, rsa.RSAPublicKey) and k.key_size <= 4096:
        n = k.public_numbers()
        return 1, n.n.to_bytes((n.n.bit_length() + 7) // 8, "big"), n.e
    if isinstance(k, ec.EllipticCurvePublicKey) and k.curve.name in ("secp256r1", "secp384r1"):
        pt = k.public_bytes(serialization.Encoding.X962, serialization.PublicFormat.UncompressedPoint)
        return (2 if k.curve.name == "secp256r1" else 3), pt, 0
    return None

def enc(subj, kind, kb, e):
    r = len(subj).to_bytes(2, "big") + subj + bytes([kind])
    return r + (len(kb).to_bytes(2, "big") + kb + e.to_bytes(4, "big") if kind == 1 else kb)

def load_existing():
    """Everything the header already holds, old full-DER form or the compact form this script writes: nothing that shipped is dropped."""
    src = open(PATH).read(); out = []
    for m in re.finditer(r"static const u8 ROOT_(\d+)\[\] = \{(.*?)\};", src, re.S):      # legacy: full certificates
        der = bytes(int(x) for x in re.findall(r"\d+", m.group(2)))
        k = key_of(x509.load_der_x509_certificate(der))
        if k: out.append((split(der), k[0], k[1], k[2]))
    m = re.search(r"trusted_roots_blob\[\] = \{(.*?)\};", src, re.S)
    if m:                                                                                  # compact: parse our own blob back
        b = bytes(int(x) for x in re.findall(r"\d+", m.group(1))); i = 0
        while i < len(b):
            nl = int.from_bytes(b[i:i + 2], "big"); i += 2; subj = b[i:i + nl]; i += nl; kind = b[i]; i += 1
            if kind == 1:
                ml = int.from_bytes(b[i:i + 2], "big"); i += 2; mod = b[i:i + ml]; i += ml; ex = int.from_bytes(b[i:i + 4], "big"); i += 4
                out.append((subj, 1, mod, ex))
            else:
                n = 65 if kind == 2 else 97; out.append((subj, kind, b[i:i + n], 0)); i += n
    return out

idents = load_existing()
# Mozilla's current bundle, then tools/extra_roots.pem (older Mozilla roots that are still valid and not distrusted for cause).
pems = re.findall(r"-----BEGIN CERTIFICATE-----.*?-----END CERTIFICATE-----", open(certifi.where()).read(), re.S)
try: pems += re.findall(r"-----BEGIN CERTIFICATE-----.*?-----END CERTIFICATE-----", open("tools/extra_roots.pem").read(), re.S)
except FileNotFoundError: pass
for pem in pems:
    c = x509.load_pem_x509_certificate(pem.encode()); k = key_of(c)
    if k: idents.append((split(c.public_bytes(serialization.Encoding.DER)), k[0], k[1], k[2]))

seen, entries = set(), []
for it in idents:
    if it in seen: continue
    seen.add(it); entries.append(enc(*it))

blob = b"".join(entries)
rows = ",\n".join("    " + ",".join(str(x) for x in blob[i:i + 24]) for i in range(0, len(blob), 24))
open(PATH, "w").write("""#ifndef TRUSTED_ROOTS_H
#define TRUSTED_ROOTS_H
#include "io.h"

/* Embedded trust anchors -- GENERATED by tools/gen_trusted_roots.py, do not edit by hand.
 *
 * Source: the roots this file held before, Mozilla's current root program (via Python's certifi) and tools/extra_roots.pem
 * (older still-valid Mozilla roots, e.g. GlobalSign Root CA R1 that Google's GTS cross-signs chain to), keeping the key
 * types x509.h can verify with: RSA up to 4096 bits and NIST P-256 / P-384.
 *
 * A trust anchor is trusted because it is in this table, not because it vouches for itself, so all that is stored is what
 * chain building uses: the raw subject Name (matched byte for byte against a certificate's issuer, exactly as x509_parse()
 * keeps it) and the public key. The root's own signature, validity dates and extensions are never consulted for an anchor, so
 * they are not kept: that is about two thirds of each certificate, and the reason this table can hold more roots than the old
 * full-DER one in less kernel.
 *
 * Entry layout (all integers big endian), entries back to back:
 *   u16 name_len, name[name_len]                       the subject Name SEQUENCE, raw DER
 *   u8  kind                                           1 = RSA, 2 = ECDSA P-256, 3 = ECDSA P-384
 *   kind 1: u16 modulus_len, modulus[] (no leading zero), u32 public exponent
 *   kind 2/3: the uncompressed point 0x04||X||Y (65 / 97 bytes)
 *
 * Anchors in this build: %d  (blob %d bytes). Keeping a CA out is a one-line edit to the list in the generator. */
#define TRUSTED_ROOT_COUNT %d
static const u32 trusted_roots_blob_len = %d;
static const u8 trusted_roots_blob[] = {
%s
};

#endif
""" % (len(entries), len(blob), len(entries), len(blob), rows))
print("anchors:", len(entries), "blob bytes:", len(blob))
