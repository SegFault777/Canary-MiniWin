"""Generates kernel/cursor_data.h: the mouse cursor shapes, from the MiniWin icon pack's Images/Cursor/*.png
(third_party/icon-bundle/, CC BY-SA 4.0, by SegFault777).

Each PNG is a tiny two-colour image with transparency: black outline, white fill. The header holds them as rows of characters
('.' transparent, 'A' outline, 'B' fill) -- the same pixel-art-as-strings form kernel/ui/cursor.h has always drawn, now with
the second colour that makes a pointer visible on any background. The result is art data derived from CC BY-SA 4.0 material, so
the generated header carries that license (not the project's GPL line) and says so.

    tools/gen_cursors.py            rewrite kernel/cursor_data.h
    tools/gen_cursors.py --check    exit 1 if the checked-in header is out of date (used by tools/test/run_host_font.sh)
"""
import os
import sys
from PIL import Image

ROOT = os.path.join(os.path.dirname(os.path.abspath(__file__)), "..")
SRC = os.path.join(ROOT, "third_party", "icon-bundle", "Images", "Cursor")
OUT = os.path.join(ROOT, "kernel", "cursor_data.h")
# (C name, PNG file). The "classic" set; a different style would be another set of files with the same shape names.
# (C name, PNG file, hot spot). The hot spot is the pixel that "is" the pointer: the arrows' tip is their top-left pixel, the hand's the tip of
# its index finger, the pen's its top-left pixel (1.1-alpha-14: it used to be the nib at the lower right, which clicked 10..13 px away from where
# the pen's corner sat), everything else is centred. "centre" = the middle pixel.
# The "classic" set; a different style would be another set of files with the same shape names.
SHAPES = [
    ("arrow",      "cursor_arrow_classic.png",          (0, 0)),
    ("help",       "cursor_arrow_help_classic.png",     (0, 0)),
    ("hand",       "cursor_hand_classic.png",           (7, 0)),
    ("ibeam",      "cursor_ibeam_classic.png",          "centre"),
    ("wait",       "cursor_wait_classic.png",           "centre"),
    ("wait_arrow", "cursor_wait_arrow_classic.png",     (0, 0)),
    ("move",       "cursor_move_classic.png",           "centre"),
    ("no",         "cursor_no_classic.png",             "centre"),
    ("pen",        "cursor_pen_classic.png",            (0, 0)),
    ("hresize",    "cursor_horizontal_classic.png",     "centre"),
    ("vresize",    "cursor_vertical_classic.png",       "centre"),
    ("diag_nwse",  "cursor_diagonal_nwse_classic.png",  "centre"),
    ("diag_nesw",  "cursor_diagonal_nesw_classic.png",  "centre"),
]


def rows_of(path):
    im = Image.open(path).convert("RGBA")
    w, h = im.size
    colors = {}
    rows = []
    for y in range(h):
        r = ""
        for x in range(w):
            px = im.getpixel((x, y))
            if px[3] == 0:
                r += "."
            elif px[3] != 255:
                sys.exit(f"{path}: partially transparent pixel at ({x},{y}) -- cursors are 1-bit alpha, no anti-aliasing")
            elif max(px[:3]) <= 24:          # black, or the near-black some of the art uses (6,6,6) / (12,12,12)
                r += "A"
            elif min(px[:3]) >= 231:
                r += "B"
            else:
                sys.exit(f"{path}: pixel ({x},{y}) is {px}, expected black (outline) or white (fill), within 24 levels")
        rows.append(r)
    return w, h, rows


def render():
    o = []
    w = o.append
    w("/* SPDX-License-Identifier: CC-BY-SA-4.0 */\n")
    w("#ifndef MW_CURSOR_DATA_H\n#define MW_CURSOR_DATA_H\n\n")
    w("/* Auto-generated by tools/gen_cursors.py from third_party/icon-bundle/Images/Cursor/*.png -- the MiniWin icon pack, by\n")
    w(" * SegFault777, licensed CC BY-SA 4.0 (https://creativecommons.org/licenses/by-sa/4.0/). This file is that artwork in another\n")
    w(" * format, so it stays under that license (see third_party/icon-bundle/NOTICE.md); the rest of the kernel is GPL-3.0-only.\n")
    w(" * Do not hand-edit: change the PNGs and re-run the script.\n")
    w(" *\n")
    w(" * One string per pixel row: '.' transparent, 'A' outline, 'B' fill. Each shape's _HX/_HY is its hot spot, the pixel that sits on the pointer\n")
    w(" * position (see SHAPES in the script). */\n\n")
    for name, png, hot in SHAPES:
        cw, ch, rows = rows_of(os.path.join(SRC, png))
        up = name.upper()
        if hot == "centre":
            hx, hy = cw // 2, ch // 2
        elif hot == "tip":
            hx, hy = max(((x, y) for y in range(ch) for x in range(cw) if rows[y][x] != "."), key=lambda p: p[0] + p[1])
        else:
            hx, hy = hot
        w(f"#define CURSOR_{up}_W {cw}\n#define CURSOR_{up}_H {ch}\n#define CURSOR_{up}_HX {hx}\n#define CURSOR_{up}_HY {hy}\n")
        w(f"static const char *const cursor_{name}[{ch}] = {{\n")
        for r in rows:
            w(f'    "{r}",\n')
        w("};\n\n")
    w("#endif\n")
    return "".join(o)


if __name__ == "__main__":
    text = render()
    if "--check" in sys.argv:
        cur = open(OUT).read() if os.path.exists(OUT) else ""
        if cur != text:
            sys.exit("kernel/cursor_data.h is out of date -- run tools/gen_cursors.py")
        print("cursor_data.h up to date")
    else:
        open(OUT, "w").write(text)
        print(f"Wrote {OUT}")
