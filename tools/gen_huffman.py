# Recover the HPACK/QPACK Huffman code table (RFC 7541 App. B) from the system's libnghttp2, then self-verify.
import ctypes, ctypes.util, sys
lib = ctypes.CDLL("libnghttp2.so.14")
class NV(ctypes.Structure):
    _fields_=[("name",ctypes.POINTER(ctypes.c_uint8)),("value",ctypes.POINTER(ctypes.c_uint8)),("namelen",ctypes.c_size_t),("valuelen",ctypes.c_size_t),("flags",ctypes.c_uint8)]
lib.nghttp2_hd_deflate_new.argtypes=[ctypes.POINTER(ctypes.c_void_p),ctypes.c_size_t]
lib.nghttp2_hd_deflate_hd.argtypes=[ctypes.c_void_p,ctypes.c_char_p,ctypes.c_size_t,ctypes.POINTER(NV),ctypes.c_size_t]
lib.nghttp2_hd_deflate_hd.restype=ctypes.c_ssize_t
lib.nghttp2_hd_inflate_new.argtypes=[ctypes.POINTER(ctypes.c_void_p)]
lib.nghttp2_hd_inflate_hd2.argtypes=[ctypes.c_void_p,ctypes.POINTER(NV),ctypes.POINTER(ctypes.c_int),ctypes.c_char_p,ctypes.c_size_t,ctypes.c_int]
lib.nghttp2_hd_inflate_hd2.restype=ctypes.c_ssize_t

def deflate(value: bytes) -> bytes:
    d=ctypes.c_void_p(); lib.nghttp2_hd_deflate_new(ctypes.byref(d),0)  # table size 0 => no indexing surprises
    name=b"x"; nv=NV(); nb=(ctypes.c_uint8*1)(*name); vb=(ctypes.c_uint8*len(value))(*value)
    nv.name=ctypes.cast(nb,ctypes.POINTER(ctypes.c_uint8)); nv.value=ctypes.cast(vb,ctypes.POINTER(ctypes.c_uint8)); nv.namelen=1; nv.valuelen=len(value); nv.flags=0x01|0x02  # NO_INDEX|NO_COPY... (flags: 1=no_index)
    nv.flags=0x01
    buf=ctypes.create_string_buffer(4096)
    n=lib.nghttp2_hd_deflate_hd(d,buf,4096,ctypes.byref(nv),1)
    assert n>0,n
    return buf.raw[:n]

def parse_value_huffman(block: bytes):
    # literal never/without indexing, literal name: 0001xxxx / 0000xxxx then name len+bytes, then value len + bytes
    i=0
    if block[0]&0xe0==0x20: i=1      # dynamic table size update (to 0) comes first
    i+=1  # first byte pattern (new name)
    nl=block[i]&0x7f; i+=1+nl   # name 'x' raw (len 1)
    b=block[i]; huff=bool(b&0x80); i+=1
    l=b&0x7f
    assert l<127
    return huff, block[i:i+l]

TWOBITS=lambda v:bin(v)[2:]
# '0' = 00000 (5 bits), verified below by encoding a run of zeros
h,data=parse_value_huffman(deflate(b"0"*16)); assert h and data==b"\x00"*10, (h,data)
codes={}
for s in range(256):
    val=bytes([s])+b"0"*40
    h,data=parse_value_huffman(deflate(val))
    assert h,("not huffman",s)
    bits="".join(f"{x:08b}" for x in data)
    last0=bits.rfind("0")
    total=last0+1
    L=total-200
    code=bits[:L]
    assert 5<=L<=30,(s,L)
    # tail must be 40 x '00000'
    assert bits[L:L+200]=="0"*200,(s,)
    codes[s]=(int(code,2),L)
codes[256]=(0x3fffffff,30)
# verify: Kraft sum == 1 and prefix-free
from fractions import Fraction
k=sum(Fraction(1,1<<L) for _,L in codes.values()); assert k==1,k
strs=sorted(f"{c:0{L}b}" for c,L in codes.values())
for a,b in zip(strs,strs[1:]): assert not b.startswith(a)
# verify by decoding single symbols and a sample sentence with libnghttp2's inflater
def inflate(block):
    inf=ctypes.c_void_p(); lib.nghttp2_hd_inflate_new(ctypes.byref(inf))
    nv=NV(); flags=ctypes.c_int(0); out=b""; buf=ctypes.create_string_buffer(block,len(block)); off=0
    res=[]
    while True:
        r=lib.nghttp2_hd_inflate_hd2(inf,ctypes.byref(nv),ctypes.byref(flags),ctypes.cast(ctypes.byref(buf,off),ctypes.c_char_p),len(block)-off,1)
        assert r>=0,r
        off+=r
        if flags.value&2: res.append((ctypes.string_at(nv.name,nv.namelen),ctypes.string_at(nv.value,nv.valuelen)))
        if flags.value&1 and off>=len(block): break
        if off>=len(block) and not flags.value&2: break
    return res
def henc(data):
    bits="".join(f"{codes[b][0]:0{codes[b][1]}b}" for b in data)
    bits+="1"*((8-len(bits)%8)%8)
    return bytes(int(bits[i:i+8],2) for i in range(0,len(bits),8))
import os,random
random.seed(1)
tests=[bytes([s]) for s in range(256)]+[os.urandom(random.randint(1,40)) for _ in range(300)]
for t in tests:
    e=henc(t); assert len(e)<127
    blk=bytes([0x00,0x01,ord('x'),0x80|len(e)])+e
    r=inflate(blk); assert r==[(b"x",t)],(t,r)
print("huffman table verified against libnghttp2: 256 single symbols + 300 random strings")
with open(sys.argv[1],"w") as f:
    f.write("/* generated by tools/gen_huffman.py -- HPACK/QPACK Huffman code (RFC 7541 Appendix B): {code, bit length} per symbol, symbol 256 = EOS */\n")
    f.write("static const u32 h3_huff_code[257] = {\n")
    for i in range(257):
        f.write(f"0x{codes[i][0]:x}u,"+("\n" if i%8==7 else " "))
    f.write("};\nstatic const u8 h3_huff_len[257] = {\n")
    for i in range(257):
        f.write(f"{codes[i][1]},"+("\n" if i%16==15 else " "))
    f.write("};\n")
