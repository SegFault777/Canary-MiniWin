"""Rasterizes Natural Earth's 1:110m land polygons (public domain) into the 1-bit world map the Time Zone tab draws.

    python3 tools/gen_worldmap.py [ne_110m_land.geojson]     # writes kernel/worldmap_data.h
    python3 tools/gen_worldmap.py --check                    # the header is what the script would write now (needs the geojson)

The GeoJSON comes from https://github.com/nvkelso/natural-earth-vector (geojson/ne_110m_land.geojson); it is not kept in this repository, only the
256x102 bitmap it produces: an equirectangular projection, longitude -180..180, latitude 84N..60S (Antarctica is left out, as on Windows 95's map).
Rendered at 4x and reduced (a cell is land when most of it is), so coastlines are not jagged. Row-major, 32 bytes a row, MSB first, 1 = land."""
import json, sys, os
from PIL import Image, ImageDraw

W, H, SS = 256, 102, 4
LAT_TOP, LAT_BOT = 84.0, -60.0
HERE = os.path.dirname(os.path.abspath(__file__))
OUT = os.path.join(HERE, "..", "kernel", "worldmap_data.h")

def render(path):
    gj = json.load(open(path))
    im = Image.new("L", (W * SS, H * SS), 0)
    d = ImageDraw.Draw(im)
    def px(lon, lat): return ((lon + 180.0) / 360.0 * W * SS, (LAT_TOP - lat) / (LAT_TOP - LAT_BOT) * H * SS)
    for f in gj["features"]:
        g = f["geometry"]
        polys = [g["coordinates"]] if g["type"] == "Polygon" else g["coordinates"]
        for poly in polys:
            for k, ring in enumerate(poly):
                d.polygon([px(x, y) for x, y in ring], fill=255 if k == 0 else 0)   # ring 0 = the land, the others = lakes cut out of it
    return im.resize((W, H), Image.BOX).point(lambda v: 255 if v >= 128 else 0)

def header(im):
    rows = []
    for y in range(H):
        bits = [1 if im.getpixel((x, y)) else 0 for x in range(W)]
        rows.append(", ".join("0x%02X" % sum(b << (7 - i) for i, b in enumerate(bits[o:o + 8])) for o in range(0, W, 8)))
    body = ",\n    ".join(rows)
    return ("/* SPDX-License-Identifier: GPL-3.0-only */\n#ifndef MW_WORLDMAP_DATA_H\n#define MW_WORLDMAP_DATA_H\n\n"
            "/* kernel/worldmap_data.h -- GENERATED by tools/gen_worldmap.py from Natural Earth 1:110m land (public domain); do not edit.\n"
            " * 256x102, equirectangular, longitude -180..180, latitude 84N..60S, 1 = land, MSB first, 32 bytes a row. */\n"
            "#define WORLDMAP_W 256\n#define WORLDMAP_H 102\n#define WORLDMAP_LAT_TOP 84\n#define WORLDMAP_LAT_BOT (-60)\n"
            "static const unsigned char worldmap_bits[WORLDMAP_H * 32] = {\n    " + body + "\n};\n\n#endif\n")

if __name__ == "__main__":
    args = [a for a in sys.argv[1:] if not a.startswith("--")]
    src = args[0] if args else "ne_110m_land.geojson"
    text = header(render(src))
    if "--check" in sys.argv:
        ok = open(OUT).read() == text
        print("worldmap_data.h", "matches" if ok else "DIFFERS"); sys.exit(0 if ok else 1)
    open(OUT, "w").write(text); print("wrote", os.path.normpath(OUT), len(text), "bytes of source")
