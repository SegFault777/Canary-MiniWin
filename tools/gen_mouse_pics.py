"""gen_mouse_pics.py -- turns the three 64x64 mouse pictures of the icon bundle (Images/64x64_other/Mouse.png, Mouse_Left.png, Mouse_Right.png) into
kernel/ui/mouse_pics.h, the pictures of Settings > Mouse > Buttons. They are far bigger than anything the icon catalog (16x16 / 32x32) holds, and
only that one page uses them, so they are compiled into the kernel: one shared palette (at most 255 colours, index 255 = transparent) and 4096 bytes
per picture. Run it after the bundle changes: tools/gen_mouse_pics.py"""
import os, sys
from PIL import Image
root = os.path.join(os.path.dirname(os.path.abspath(__file__)), "..")
names = ["Mouse", "Mouse_Left", "Mouse_Right"]
imgs = []
for n in names:
    im = Image.open(os.path.join(root, "third_party/icon-bundle/Images/64x64_other", n + ".png")).convert("RGBA")
    if im.size != (64, 64): sys.exit(f"{n}.png: expected 64x64, got {im.size}")
    imgs.append(im)
pal = []
for im in imgs:
    for (r, g, b, a) in im.getdata():
        if a >= 128 and (r, g, b) not in pal: pal.append((r, g, b))
if len(pal) > 255: sys.exit(f"too many colours: {len(pal)}")
out = os.path.join(root, "kernel/ui/mouse_pics.h")
with open(out, "w") as f:
    f.write("/* SPDX-License-Identifier: GPL-3.0-only */\n/* GENERATED by tools/gen_mouse_pics.py from third_party/icon-bundle/Images/64x64_other/ -- do not edit. */\n")
    f.write("#ifndef MW_UI_MOUSE_PICS_H\n#define MW_UI_MOUSE_PICS_H\n#define MOUSE_PIC_W 64\n#define MOUSE_PIC_H 64\n#define MOUSE_PIC_TRANSPARENT 255\n#define MOUSE_PIC_COUNT 3        /* 0 neutral, 1 left button highlighted, 2 right button highlighted */\n")
    f.write(f"static const unsigned int mouse_pic_pal[{len(pal)}] = {{\n    " + ", ".join(f"0x{r:02X}{g:02X}{b:02X}" for r, g, b in pal) + "\n};\n")
    f.write("static const unsigned char mouse_pic[MOUSE_PIC_COUNT][64 * 64] = {\n")
    for im in imgs:
        f.write("  {\n")
        px = list(im.getdata())
        for y in range(64):
            f.write("    " + ",".join(str(255 if px[y*64+x][3] < 128 else pal.index(px[y*64+x][:3])) for x in range(64)) + ",\n")
        f.write("  },\n")
    f.write("};\n#endif\n")
print(f"gen_mouse_pics: {len(pal)} colours -> {out}")
