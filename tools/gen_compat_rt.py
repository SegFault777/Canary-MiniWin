# gen_compat_rt.py ELF BIN OUT.h -- turns the compiled classic-program runtime (kernel/compat_rt.c) into a C header the kernel includes: the bytes of the
# page, and where compat_start / compat_entry_ptr are inside it. The blob must fit the one page at 0x8F0000 (the loader slot starts at 0x8F1000).
import subprocess, sys
elf, binf, out = sys.argv[1:4]
data = open(binf, "rb").read()
if len(data) > 4096:
    print(f"gen_compat_rt: the runtime is {len(data)} bytes, more than the one page (4096) at 0x8F0000"); sys.exit(1)
syms = {}
for line in subprocess.check_output(["nm", elf], text=True).splitlines():
    p = line.split()
    if len(p) == 3: syms[p[2]] = int(p[0], 16)
for need in ("compat_start", "compat_entry_ptr", "mw3_table"):
    if need not in syms:
        print(f"gen_compat_rt: symbol {need} missing"); sys.exit(1)
if syms["mw3_table"] != 0x8F0000:
    print(f"gen_compat_rt: the table must be at 0x8F0000 (it is at 0x{syms['mw3_table']:X})"); sys.exit(1)
with open(out, "w") as f:
    f.write("/* SPDX-License-Identifier: GPL-3.0-only */\n/* GENERATED by tools/gen_compat_rt.py from kernel/compat_rt.c -- do not edit, do not commit. */\n")
    f.write("#ifndef MW_COMPAT_RT_BLOB_H\n#define MW_COMPAT_RT_BLOB_H\n")
    f.write(f"#define COMPAT_RT_SIZE {len(data)}u\n#define COMPAT_RT_START 0x{syms['compat_start']:X}u\n#define COMPAT_RT_ENTRY_PTR 0x{syms['compat_entry_ptr']:X}u\n")
    f.write("static const unsigned char compat_rt_blob[COMPAT_RT_SIZE] = {\n")
    for i in range(0, len(data), 16):
        f.write("    " + ",".join(str(b) for b in data[i:i+16]) + ",\n")
    f.write("};\n#endif\n")
print(f"gen_compat_rt: {len(data)} bytes, start 0x{syms['compat_start']:X}")
